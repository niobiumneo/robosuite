def test_asset_size_budget():
    sizes = [os.path.getsize(os.path.join(r, f)) for r, _, fs in os.walk(PKG) for f in fs]
    gdir = os.path.join(ASSETS, "grippers", "meshes", "pal_pro_gripper")
    sizes += [os.path.getsize(os.path.join(gdir, f)) for f in os.listdir(gdir)]
    sizes += [os.path.getsize(os.path.join(TIAGO, f)) for f in os.listdir(TIAGO) if os.path.isfile(os.path.join(TIAGO, f))]
    total = sum(sizes)
    print("\nTIAGo Pro assets: %.2f MB in %d files, largest %.0f kB" % (total / 1e6, len(sizes), max(sizes) / 1e3))
    assert total <= 8.5e6  # 8.47 MB incl. 1.1 MB of gripper meshes duplicated next to grippers/pal_pro_gripper.xml
    assert max(sizes) <= 1.0e6

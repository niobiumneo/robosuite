ASSETS = os.path.join(os.path.dirname(robosuite.__file__), "models", "assets")
TIAGO = os.path.join(ASSETS, "robots", "tiago_pro")
PKG = os.path.join(TIAGO, "pal_tiago_pro")
GRIPPER_XML = os.path.join(ASSETS, "grippers", "pal_pro_gripper.xml")
REPO = os.path.abspath(os.path.join(os.path.dirname(robosuite.__file__), ".."))
OTYPE = mujoco.mjtObj


def nm(m, t, i):
    return mujoco.mj_id2name(m, t, i) or ""


@pytest.fixture(scope="module")
def ov():
    tools = os.path.join(REPO, "tools", "tiago_pro")
    if not os.path.isdir(tools):
        pytest.skip("tools/tiago_pro is not part of the installed package")
    sys.path.insert(0, tools)
    try:
        import overlay
    finally:
        sys.path.remove(tools)
    return overlay


@pytest.fixture(scope="module")
def pkg():
    m = mujoco.MjModel.from_xml_path(os.path.join(PKG, "tiago_pro.xml"))
    return m, mujoco.MjData(m)


@pytest.fixture(scope="module")
def merged():
    """robot_right.xml + gripper merged the way robosuite does it (flat defaults, MujocoXML loader)."""

    # a PalProGripper instance merged into the robot at right_hand, like ManipulatorModel.add_gripper
    rob = MujocoXML(os.path.join(TIAGO, "robot_right.xml"))
    g = PalProGripper(idn="0_right")
    rob.merge(g, merge_body="right_hand")
    m = rob.get_model()
    return m, mujoco.MjData(m)


def pkg_set(pm, pd, q_arm, ov, finger=None):
    pd.qpos[:] = pm.qpos0
    pd.qpos[2] = 0.0  # robot_right sits on the floor (package root is 2 mm above it)
    j = lambda n: pm.jnt_qposadr[mujoco.mj_name2id(pm, OTYPE.mjOBJ_JOINT, n)]
    pd.qpos[j("torso_lift_joint")] = ov.PARK_TORSO
    pd.qpos[j("head_1_joint")], pd.qpos[j("head_2_joint")] = ov.PARK_HEAD
    for i, v in enumerate(ov.LEFT_PARK):
        pd.qpos[j("arm_left_%d_joint" % (i + 1))] = v
    pd.qpos[j("gripper_left_finger_joint")] = ov.PARK_LEFT_GRIPPER
    for i in range(7):
        pd.qpos[j("arm_right_%d_joint" % (i + 1))] = q_arm[i]
    if finger is not None:
        pd.qpos[j("gripper_right_finger_joint")] = finger
        for e in range(pm.neq):
            if pm.eq_type[e] == 2 and nm(pm, OTYPE.mjOBJ_JOINT, pm.eq_obj2id[e]).startswith("gripper_right"):
                pd.qpos[j(nm(pm, OTYPE.mjOBJ_JOINT, pm.eq_obj2id[e]))] = finger / pm.eq_data[e, 1]
    mujoco.mj_forward(pm, pd)


